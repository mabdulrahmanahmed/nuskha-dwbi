"""Reverse-engineer a source database from its live catalog (unit 3.09). Synthetic data.

For one department per engine (Sales on MySQL, Purchasing on PostgreSQL, Inventory on SQLite)
this reads the catalog through SQLAlchemy's inspector, without looking at our DDL files, and writes
to evidence/04_metadata_lineage/reverse_engineering/:
  <dept>_erd.png / .dot     ERD of what the catalog says
  <dept>_draft_ddl.sql      draft CREATE TABLE statements rebuilt from the catalog
  <dept>_links.csv          every relationship, marked
                              observed  = declared foreign key found in the catalog
                              inferred  = guessed: a column named like another table's
                                          single-column primary key (e.g. stock_count.item_id)

  python -m src.reverse_engineer inventory          # one department
  python -m src.reverse_engineer                    # sales, purchasing, inventory
"""
from __future__ import annotations

import sys

import pandas as pd

from src.common import evidence_dir, get_engine
from src.erd import Column, Table, draw_matplotlib, to_dot

DEPTS = {"sales": ("sales", "MySQL sales_db"), "purchasing": ("purchasing", "PostgreSQL purchasing_db"),
         "inventory": ("inventory", "SQLite inventory.db")}


def read_catalog(engine_name: str) -> dict:
    from sqlalchemy import inspect

    insp = inspect(get_engine(engine_name))
    tables = {}
    for name in sorted(insp.get_table_names()):
        pk = set(insp.get_pk_constraint(name).get("constrained_columns") or [])
        fks = {}
        for fk in insp.get_foreign_keys(name):
            for c, rc in zip(fk["constrained_columns"], fk["referred_columns"]):
                fks[c] = (fk["referred_table"], rc)
        t = Table(name)
        for col in insp.get_columns(name):
            t.columns.append(Column(col["name"], str(col["type"]), col["name"] in pk, fks.get(col["name"])))
        tables[name] = t
    return tables


def links(tables: dict) -> pd.DataFrame:
    rows = [{"child_table": t.name, "child_column": c.name, "parent_table": c.fk[0], "parent_column": c.fk[1],
             "status": "observed", "evidence": "declared foreign key in the catalog"}
            for t in tables.values() for c in t.columns if c.fk]
    observed = {(r["child_table"], r["child_column"]) for r in rows}
    pks = {t.name: [c.name for c in t.columns if c.pk] for t in tables.values()}
    for t in tables.values():
        for c in t.columns:
            if c.pk or (t.name, c.name) in observed:
                continue
            for parent, cols in pks.items():
                if parent != t.name and cols == [c.name]:
                    rows.append({"child_table": t.name, "child_column": c.name, "parent_table": parent,
                                 "parent_column": c.name, "status": "inferred",
                                 "evidence": f"column name equals the primary key of {parent}; no FK declared"})
    return pd.DataFrame(rows, columns=["child_table", "child_column", "parent_table", "parent_column",
                                       "status", "evidence"])


def draft_ddl(tables: dict, link_df: pd.DataFrame, title: str) -> str:
    out = [f"-- Draft DDL reverse-engineered from the live catalog: {title}",
           "-- Generated by src/reverse_engineer.py (synthetic data, seed 472). Inferred links are comments only.", ""]
    for t in tables.values():
        defs = [f"  {c.name} {c.type}" for c in t.columns]
        pk = [c.name for c in t.columns if c.pk]
        if pk:
            defs.append(f"  PRIMARY KEY ({', '.join(pk)})")
        for c in t.columns:
            if c.fk:
                defs.append(f"  FOREIGN KEY ({c.name}) REFERENCES {c.fk[0]} ({c.fk[1]})")
        out.append(f"CREATE TABLE {t.name} (\n" + ",\n".join(defs) + "\n);")
        for r in link_df[(link_df.child_table == t.name) & (link_df.status == "inferred")].itertuples():
            out.append(f"-- inferred: {t.name}.{r.child_column} -> {r.parent_table}.{r.parent_column} (name match)")
        out.append("")
    return "\n".join(out)


def reverse_engineer(dept: str) -> dict:
    engine_name, title = DEPTS[dept]
    tables = read_catalog(engine_name)
    link_df = links(tables)
    out = evidence_dir("04_metadata_lineage") / "reverse_engineering"
    out.mkdir(parents=True, exist_ok=True)
    full_title = f"{dept.capitalize()} ({title}), reverse-engineered from the catalog"
    (out / f"{dept}_draft_ddl.sql").write_text(draft_ddl(tables, link_df, title), encoding="utf-8", newline="\n")
    (out / f"{dept}_erd.dot").write_text(to_dot(tables, full_title), encoding="utf-8", newline="\n")
    draw_matplotlib(tables, full_title, out / f"{dept}_erd.png")
    link_df.to_csv(out / f"{dept}_links.csv", index=False, lineterminator="\n")
    return {"department": dept, "engine": title, "tables": len(tables),
            "observed_links": int((link_df.status == "observed").sum()),
            "inferred_links": int((link_df.status == "inferred").sum())}


if __name__ == "__main__":
    depts = sys.argv[1:] or list(DEPTS)
    res = pd.DataFrame([reverse_engineer(d) for d in depts])
    print(res.to_string(index=False))
