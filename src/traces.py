"""Six end-to-end traces from a warehouse figure back to a source row (unit 3.10). Synthetic data.

The warehouse side of each trace is in sql/05_traces/T*.sql (steps separated by '-- step:'
comments). The last hops cross database engines, so they run here: the raw snapshot CSV the
extract wrote, then the row in MySQL, PostgreSQL or SQLite. Every trace must end at a source row.

  python -m src.traces     # -> evidence/04_metadata_lineage/traces/T1..T6.md + trace_summary.csv
"""
from __future__ import annotations

import pandas as pd
from sqlalchemy import text

from src.common import SQL_DIR, evidence_dir, get_engine, write_evidence
from src.raw import batch_dir, read_csv_text

OUT = evidence_dir("04_metadata_lineage") / "traces"
OUT.mkdir(parents=True, exist_ok=True)


def sql_steps(name: str) -> list[tuple[str, str]]:
    """[(step title, SQL)] from a trace file."""
    body = (SQL_DIR / "05_traces" / f"{name}.sql").read_text(encoding="utf-8")
    steps = []
    for chunk in body.split("-- step:")[1:]:
        title, sql = chunk.split("\n", 1)
        steps.append((title.strip(), sql.strip().rstrip(";")))
    return steps


def q(engine: str, sql: str, **params) -> pd.DataFrame:
    with get_engine(engine).connect() as con:
        if engine == "purchasing":
            con.execute(text("SET TIME ZONE 'Asia/Karachi'"))
        return pd.read_sql(text(sql), con, params=params)


def raw_row(batch_id: int, db: str, table: str, keys: dict) -> pd.DataFrame:
    df = read_csv_text(batch_dir(batch_id) / f"{db}.{table}.csv")
    for k, v in keys.items():
        df = df[df[k] == str(v)]
    return df


class Trace:
    def __init__(self, tid: str, title: str):
        self.tid, self.title, self.parts, self.ends_at_source = tid, title, [], False

    def step(self, title: str, df: pd.DataFrame, sql: str | None = None, source: bool = False) -> pd.DataFrame:
        self.parts.append((title, sql, df))
        if source and len(df):
            self.ends_at_source = True
        return df

    def run_sql(self, name: str, **params) -> list[pd.DataFrame]:
        return [self.step(t, q("dw", s, **params), s) for t, s in sql_steps(name)]

    def write(self) -> dict:
        lines = [f"# {self.tid} {self.title}", "", "Synthetic data (seed 472). Generated by `python -m src.traces`.", ""]
        for i, (title, sql, df) in enumerate(self.parts, 1):
            lines.append(f"## Step {i}: {title}")
            if sql:
                lines += ["", "```sql", sql, "```"]
            shown = df.drop(columns=[c for c in df.columns if c == "raw_json"], errors="ignore")
            lines += ["", shown.head(10).to_markdown(index=False, floatfmt=".2f") if len(shown) else "_no rows_", ""]
        lines.append(f"**Ends at a source row:** {'yes' if self.ends_at_source else 'NO'}")
        (OUT / f"{self.tid}.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
        return {"trace": self.tid, "title": self.title, "steps": len(self.parts),
                "ends_at_source_row": self.ends_at_source, "result": "PASS" if self.ends_at_source else "FAIL"}


def pick(sql: str) -> str:
    return q("dw", sql).iloc[0, 0]


def t1() -> dict:
    key = pick("SELECT min(f.source_key) FROM dw.fact_sales f JOIN dw.dim_customer c USING (customer_key) "
               "WHERE f.batch_id = 2 AND f.date_key >= 20260901 AND c.customer_type = 'LOYALTY' AND NOT f.is_cancelled")
    r, ln = key.split("|")
    t = Trace("T1", f"A normal till receipt line ({key})")
    t.run_sql("T1_receipt_line", source_key=key)
    t.step("raw snapshot CSV (evidence/02_etl/raw/batch_2/sales_db.receipt_line.csv)",
           raw_row(2, "sales_db", "receipt_line", {"receipt_no": r, "line_no": ln}))
    t.step("source row in MySQL sales_db.receipt_line",
           q("sales", "SELECT * FROM receipt_line WHERE receipt_no = :r AND line_no = :l", r=r, l=int(ln)), source=True)
    t.step("its header in MySQL sales_db.receipt", q("sales", "SELECT * FROM receipt WHERE receipt_no = :r", r=r))
    return t.write()


def t2() -> dict:
    key = pick("SELECT min(source_key) FROM dw.fact_purchase WHERE currency_code = 'USD' AND batch_id = 2 AND NOT is_cancelled")
    g, ln = key.split("|")
    t = Trace("T2", f"A USD purchase line ({key})")
    fact = t.run_sql("T2_usd_purchase_line", source_key=key)[0]
    t.step("raw snapshot CSV (evidence/02_etl/raw/batch_2/purchasing_db.grn_line.csv)",
           raw_row(2, "purchasing_db", "grn_line", {"grn_no": g, "line_no": ln}))
    t.step("source row in PostgreSQL purchasing_db.grn_line",
           q("purchasing", "SELECT * FROM grn_line WHERE grn_no = :g AND line_no = :l", g=g, l=int(ln)), source=True)
    t.step("its goods receipt and purchase order (currency) in PostgreSQL",
           q("purchasing", "SELECT gr.grn_no, gr.received_at, po.po_no, po.currency, po.supplier_id FROM goods_receipt gr "
                           "JOIN purchase_order po USING (po_no) WHERE gr.grn_no = :g", g=g))
    t.step("rate used, from MySQL finance_db.fx_rate (latest rate on or before the receipt date)",
           q("finance", "SELECT * FROM fx_rate WHERE rate_date <= :d ORDER BY rate_date DESC LIMIT 1",
             d=fact.full_date.iloc[0]), source=True)
    return t.write()


def t3() -> dict:
    rno = pick("SELECT min(f.receipt_no) FROM dw.fact_sales f WHERE f.batch_id = 2 AND f.date_key < 20260901 "
               "AND NOT EXISTS (SELECT 1 FROM meta.lineage l WHERE l.warehouse_table = 'dw.fact_sales' "
               "AND l.source_key = f.source_key AND l.batch_id = 1) AND f.receipt_no IN "
               "(SELECT receipt_no FROM stg.receipt WHERE updated_at > '2026-08-31 23:59:59' "
               "AND receipt_ts <= '2026-08-31 23:59:59')")
    t = Trace("T3", f"A late receipt loaded in batch 2 ({rno})")
    t.run_sql("T3_late_receipt", receipt_no=rno)
    t.step("raw snapshot CSV of batch 2 (evidence/02_etl/raw/batch_2/sales_db.receipt.csv)",
           raw_row(2, "sales_db", "receipt", {"receipt_no": rno}))
    t.step("not in batch 1's snapshot (it was not saved yet)", raw_row(1, "sales_db", "receipt", {"receipt_no": rno}))
    t.step("source row in MySQL sales_db.receipt (receipt_ts before, updated_at after the batch-1 cut-off)",
           q("sales", "SELECT receipt_no, branch_name, receipt_ts, status, updated_at FROM receipt "
                      "WHERE receipt_no = :r", r=rno), source=True)
    return t.write()


def t4() -> dict:
    key = pick("SELECT min(f.source_key) FROM dw.fact_sales f JOIN dw.dim_product p USING (product_key) "
               "WHERE p.category = 'Diabetes Care' AND f.date_key BETWEEN 20260301 AND 20260331 AND NOT f.is_cancelled")
    r, ln = key.split("|")
    t = Trace("T4", f"Derived measure gross_margin_pkr ({key})")
    fact, hist = t.run_sql("T4_gross_margin", source_key=key)
    check = pd.DataFrame([{
        "net_amount_pkr (Sales)": fact.net_amount_pkr.iloc[0], "quantity": fact.quantity_units.iloc[0],
        "std cost on the date (Inventory)": hist.std_cost_per_unit.iloc[0],
        "recomputed cost": round(float(fact.quantity_units.iloc[0]) * float(hist.std_cost_per_unit.iloc[0]), 2),
        "recomputed margin": round(float(fact.net_amount_pkr.iloc[0])
                                   - round(float(fact.quantity_units.iloc[0]) * float(hist.std_cost_per_unit.iloc[0]), 2), 2),
        "stored margin": fact.gross_margin_pkr.iloc[0]}])
    t.step("recomputation: net - quantity x cost on the date = stored margin", check)
    t.step("Sales source row in MySQL sales_db.receipt_line",
           q("sales", "SELECT * FROM receipt_line WHERE receipt_no = :r AND line_no = :l", r=r, l=int(ln)), source=True)
    item = int(fact.product_code.iloc[0][2:])
    t.step("Inventory source rows in SQLite item_cost_history (DD/MM/YYYY text dates)",
           q("inventory", "SELECT * FROM item_cost_history WHERE item_id = :i", i=item), source=True)
    return t.write()


def t5() -> dict:
    t = Trace("T5", "Dashboard total: FY2026 net sales card")
    card = t.run_sql("T5_fy2026_card")[0]
    src = q("sales", "SELECT l.receipt_no, l.line_no, r.status, "
                     "l.qty * l.unit_price_pkr - COALESCE(l.discount_pkr, 0) AS net FROM receipt_line l "
                     "JOIN receipt r USING (receipt_no) WHERE r.receipt_ts BETWEEN '2025-07-01' AND '2026-06-30 23:59:59'")
    src["source_key"] = src.receipt_no + "|" + src.line_no.astype(str)
    facts = q("dw", "SELECT f.source_key, f.net_amount_pkr, f.receipt_no, f.is_cancelled FROM dw.fact_sales f "
                    "JOIN dw.dim_date d USING (date_key) WHERE d.fiscal_year = 'FY2026'")
    rejected = set(q("dw", "SELECT source_key FROM etl.rejects WHERE source_table = 'receipt_line'").source_key)
    deleted = set(q("dw", "SELECT source_key FROM etl.deletion_log").source_key)
    in_fact = set(facts.source_key)
    bridge = [
        ("MySQL: every line of receipts dated in FY2026", len(src), src.net.astype(float).sum()),
        ("minus lines of VOIDED receipts (kept in the fact, flagged is_cancelled)",
         -int((src.status == "VOIDED").sum()), -src.net[src.status == "VOIDED"].astype(float).sum()),
        ("minus lines quarantined in etl.rejects",
         -int((src.source_key.isin(rejected) & ~src.source_key.isin(in_fact) & (src.status != "VOIDED")).sum()),
         -src.net[src.source_key.isin(rejected) & ~src.source_key.isin(in_fact) & (src.status != "VOIDED")]
         .astype(float).sum()),
        ("plus lines of receipts later hard-deleted at the till (logged, kept in the warehouse)",
         int((facts.receipt_no.isin(deleted) & ~facts.is_cancelled).sum()),
         facts.net_amount_pkr[facts.receipt_no.isin(deleted) & ~facts.is_cancelled].astype(float).sum()),
    ]
    b = pd.DataFrame(bridge, columns=["step", "lines", "net_pkr"])
    total = pd.DataFrame([{"step": "= warehouse card (vw_sales_enriched, FY2026)", "lines": int(b.lines.sum()),
                           "net_pkr": round(b.net_pkr.sum(), 2)}])
    b = pd.concat([b, total], ignore_index=True)
    b["net_pkr"] = b.net_pkr.round(2)
    t.step("bridge from the MySQL source rows to the card", b, source=True)
    ok = abs(float(card.net_sales_pkr.iloc[0]) - float(total.net_pkr.iloc[0])) < 0.01 and \
        int(card.lines.iloc[0]) == int(total.lines.iloc[0])
    t.step("bridge result equals the card", pd.DataFrame([{"card_pkr": float(card.net_sales_pkr.iloc[0]),
                                                           "bridge_pkr": float(total.net_pkr.iloc[0]),
                                                           "card_lines": int(card.lines.iloc[0]),
                                                           "bridge_lines": int(total.lines.iloc[0]), "equal": ok}]))
    t.step("one of the source rows (MySQL sales_db.receipt_line)",
           q("sales", "SELECT * FROM receipt_line WHERE receipt_no = :r AND line_no = :l",
             r=src.receipt_no.iloc[0], l=int(src.line_no.iloc[0])), source=True)
    t.ends_at_source = t.ends_at_source and ok
    return t.write()


def t6() -> dict:
    t = Trace("T6", "AI input series: vw_forecast_features, March 2026")
    feat, facts = t.run_sql("T6_forecast_input", month_start="2026-03-01")
    t.step("feature value = sum of the fact rows", pd.DataFrame([{
        "view net_sales_pkr": float(feat.net_sales_pkr.iloc[0]), "fact rows sum": float(facts.net_sales_pkr.iloc[0]),
        "equal": abs(float(feat.net_sales_pkr.iloc[0]) - float(facts.net_sales_pkr.iloc[0])) < 0.005}]))
    r, ln = facts.first_source_key.iloc[0].split("|")
    t.step("one of those fact rows in MySQL sales_db.receipt_line",
           q("sales", "SELECT * FROM receipt_line WHERE receipt_no = :r AND line_no = :l", r=r, l=int(ln)), source=True)
    return t.write()


def main() -> pd.DataFrame:
    from src.etl_db import record_checks

    out = pd.DataFrame([f() for f in (t1, t2, t3, t4, t5, t6)])
    write_evidence("04_metadata_lineage", "traces/trace_summary.csv", out)
    record_checks(2, [{"check": f"trace {r.trace}: ends at a source row", "expected": True,
                       "actual": r.ends_at_source_row, "result": r.result} for r in out.itertuples()])
    print(out.to_string(index=False))
    if (out.result == "FAIL").any():
        raise SystemExit(1)
    return out


if __name__ == "__main__":
    main()
